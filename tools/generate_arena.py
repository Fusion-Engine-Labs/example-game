        ("Target Sniper", (16, 1.3, -18), 0.55, 1, 300, (0, 0, 0), 0, 0, True),
        ("Target Patrol", (9.5, 1.4, -3), 1.0, 1, 150, (0, 0, 3), 1.0, 0, True),
        ("Target Big Floater", (0, 5.5, -11), 1.5, 3, 300, (7, 0, 0), 0.6, 0, True),
