#!/usr/bin/env python3
"""Generate the meshes, texture, materials, and scene for the arena FPS.

Everything here is built from primitives, so the script has no dependencies
beyond the standard library and is safe to re-run: asset and entity IDs are
derived deterministically, so regenerating never breaks scene references.

Outputs (relative to the project root):
  assets/meshes/arena_*.gltf/.bin, blaster, bolt, spark, muzzle_flash,
    target, crosshair, hit_marker, sky_dome
  assets/textures/arena_grid.png, arena_sky.png
  assets/materials/<mesh>_<material>.zamat, only for materials that need
    settings glTF cannot express (see `pbr`)
  scenes/arena.scene.json

Every other material is generated by the asset cooker from the glTF.
"""

import hashlib
import json
import math
import struct
import uuid
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
MESH_DIR = ASSETS / "meshes"
TEXTURE_DIR = ASSETS / "textures"
MATERIAL_DIR = ASSETS / "materials"
SCENE_PATH = ROOT / "scenes" / "arena.scene.json"

PROJECT_ID = json.loads((ROOT / ".fusion" / "fusion.proj").read_text())["project_id"]


def asset_id(relative_path):
    """Same derivation as zimp's AssetId.derive(project_id, path)."""
    namespace = uuid.UUID(PROJECT_ID).bytes
    digest = bytearray(hashlib.sha256(namespace + relative_path.encode()).digest()[:16])
    digest[6] = (digest[6] & 0x0F) | 0x80
    digest[8] = (digest[8] & 0x3F) | 0x80
    return str(uuid.UUID(bytes=bytes(digest)))


def stable_uuid(name):
    return str(uuid.uuid5(uuid.UUID(PROJECT_ID), "arena/" + name))


# --------------------------------------------------------------- geometry


def empty():
    return {"positions": [], "normals": [], "uvs": [], "indices": []}


def merge(*geometries):
    result = empty()
    for geometry in geometries:
        base = len(result["positions"])
        result["positions"].extend(geometry["positions"])
        result["normals"].extend(geometry["normals"])
        result["uvs"].extend(geometry["uvs"])
        result["indices"].extend(base + index for index in geometry["indices"])
    return result


def box(center, size, uv_tile=None):
    """Axis-aligned box. With `uv_tile` (meters per texture repeat) UVs follow
    world size so a texture tiles evenly instead of stretching."""
    cx, cy, cz = center
    x, y, z = (dimension / 2 for dimension in size)
    sx, sy, sz = size
    # (corners, normal, (u extent, v extent))
    faces = [
        (((-x, -y, z), (x, -y, z), (x, y, z), (-x, y, z)), (0, 0, 1), (sx, sy)),
        (((x, -y, -z), (-x, -y, -z), (-x, y, -z), (x, y, -z)), (0, 0, -1), (sx, sy)),
        (((x, -y, z), (x, -y, -z), (x, y, -z), (x, y, z)), (1, 0, 0), (sz, sy)),
        (((-x, -y, -z), (-x, -y, z), (-x, y, z), (-x, y, -z)), (-1, 0, 0), (sz, sy)),
        (((-x, y, z), (x, y, z), (x, y, -z), (-x, y, -z)), (0, 1, 0), (sx, sz)),
        (((-x, -y, -z), (x, -y, -z), (x, -y, z), (-x, -y, z)), (0, -1, 0), (sx, sz)),
    ]
    geometry = empty()
    for corners, normal, (u_size, v_size) in faces:
        base = len(geometry["positions"])
        geometry["positions"].extend((cx + vx, cy + vy, cz + vz) for vx, vy, vz in corners)
        geometry["normals"].extend([normal] * 4)
        u, v = (u_size / uv_tile, v_size / uv_tile) if uv_tile else (1, 1)
        geometry["uvs"].extend(((0, v), (u, v), (u, 0), (0, 0)))
        geometry["indices"].extend((base, base + 1, base + 2, base, base + 2, base + 3))
    return geometry


def cylinder(radius, length, segments=16):
    """Cylinder along Z centered at the origin, capped at both ends."""
    geometry = empty()
    half = length / 2
    for i in range(segments + 1):
        angle = i * math.tau / segments
        x, y = math.cos(angle) * radius, math.sin(angle) * radius
        geometry["positions"].extend(((x, y, half), (x, y, -half)))
        geometry["normals"].extend(((math.cos(angle), math.sin(angle), 0),) * 2)
        geometry["uvs"].extend(((i / segments, 0), (i / segments, 1)))
    for i in range(segments):
        base = i * 2
        geometry["indices"].extend((base, base + 2, base + 3, base, base + 3, base + 1))

    for normal_z, z in ((1, half), (-1, -half)):
        center = len(geometry["positions"])
        geometry["positions"].append((0, 0, z))
        geometry["normals"].append((0, 0, normal_z))
        geometry["uvs"].append((0.5, 0.5))
        ring = len(geometry["positions"])
        for i in range(segments):
            angle = i * math.tau / segments
            x, y = math.cos(angle) * radius, math.sin(angle) * radius
            geometry["positions"].append((x, y, z))
            geometry["normals"].append((0, 0, normal_z))
            geometry["uvs"].append((x / radius * 0.5 + 0.5, y / radius * 0.5 + 0.5))
        for i in range(segments):
            current, following = ring + i, ring + (i + 1) % segments
            if normal_z > 0:
                geometry["indices"].extend((center, current, following))
            else:
                geometry["indices"].extend((center, following, current))
    return geometry


def sphere(radius, segments=16, rings=10, stretch_z=1.0):
    """UV sphere, optionally stretched along Z into an ellipsoid."""
    geometry = empty()
    for ring in range(rings + 1):
        phi = math.pi * ring / rings
        for segment in range(segments + 1):
            theta = math.tau * segment / segments
            nx = math.sin(phi) * math.cos(theta)
            ny = math.cos(phi)
            nz = math.sin(phi) * math.sin(theta)
            geometry["positions"].append((nx * radius, ny * radius, nz * radius * stretch_z))
            normal = (nx, ny, nz / stretch_z)
            length = math.sqrt(sum(c * c for c in normal)) or 1
            geometry["normals"].append(tuple(c / length for c in normal))
            geometry["uvs"].append((segment / segments, ring / rings))
    stride = segments + 1
    for ring in range(rings):
        for segment in range(segments):
            a = ring * stride + segment
            b = a + stride
            geometry["indices"].extend((a, a + 1, b, a + 1, b + 1, b))
    return geometry


def octahedron(radius):
    tips = [(radius, 0, 0), (-radius, 0, 0), (0, radius, 0), (0, -radius, 0), (0, 0, radius), (0, 0, -radius)]
    faces = [(0, 2, 4), (2, 1, 4), (1, 3, 4), (3, 0, 4), (2, 0, 5), (1, 2, 5), (3, 1, 5), (0, 3, 5)]
    geometry = empty()
    for a, b, c in faces:
        pa, pb, pc = tips[a], tips[b], tips[c]
        u = [pb[i] - pa[i] for i in range(3)]
        v = [pc[i] - pa[i] for i in range(3)]
        n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        length = math.sqrt(sum(x * x for x in n))
        n = tuple(x / length for x in n)
        base = len(geometry["positions"])
        geometry["positions"].extend((pa, pb, pc))
        geometry["normals"].extend((n, n, n))
        geometry["uvs"].extend(((0, 0), (1, 0), (0.5, 1)))
        geometry["indices"].extend((base, base + 1, base + 2))
    return geometry


def quad(center, size, normal=(0, 0, 1)):
    """Flat rectangle in the XY plane facing +Z (or the given axis normal)."""
    cx, cy, cz = center
    x, y = size[0] / 2, size[1] / 2
    geometry = empty()
    geometry["positions"] = [(cx - x, cy - y, cz), (cx + x, cy - y, cz), (cx + x, cy + y, cz), (cx - x, cy + y, cz)]
    geometry["normals"] = [normal] * 4
    geometry["uvs"] = [(0, 1), (1, 1), (1, 0), (0, 0)]
    geometry["indices"] = [0, 1, 2, 0, 2, 3]
    return geometry


def transformed(geometry, rotate=None, offset=(0, 0, 0)):
    """Copy of `geometry` rotated by `rotate` (a function on 3-tuples) then moved."""
    rotate = rotate or (lambda v: v)
    ox, oy, oz = offset
    result = empty()
    result["positions"] = [tuple(a + b for a, b in zip(rotate(p), (ox, oy, oz))) for p in geometry["positions"]]
    result["normals"] = [rotate(n) for n in geometry["normals"]]
    result["uvs"] = list(geometry["uvs"])
    result["indices"] = list(geometry["indices"])
    return result


def rotate_x(angle):
    c, s = math.cos(angle), math.sin(angle)
    return lambda v: (v[0], v[1] * c - v[2] * s, v[1] * s + v[2] * c)


def rotate_y(angle):
    c, s = math.cos(angle), math.sin(angle)
    return lambda v: (v[0] * c + v[2] * s, v[1], -v[0] * s + v[2] * c)


def rotate_z(angle):
    c, s = math.cos(angle), math.sin(angle)
    return lambda v: (v[0] * c - v[1] * s, v[0] * s + v[1] * c, v[2])


# --------------------------------------------------------------- glTF writer


def write_gltf(name, parts, materials, images=()):
    """Writes assets/meshes/<name>.gltf + .bin and a .zamat per material.
    `parts` is a list of (geometry, material index); each becomes one
    primitive of one mesh. `images` are texture paths relative to assets/."""
    blob = bytearray()
    buffer_views = []
    accessors = []

    def accessor(values, component_type, value_type, target, bounds=False):
        while len(blob) % 4:
            blob.append(0)
        offset = len(blob)
        count = {"SCALAR": 1, "VEC2": 2, "VEC3": 3}[value_type]
        fmt = {5123: "H", 5126: "f"}[component_type]
        flat = [c for value in values for c in (value if isinstance(value, tuple) else (value,))]
        blob.extend(struct.pack("<" + fmt * len(flat), *flat))
        buffer_views.append({"buffer": 0, "byteOffset": offset, "byteLength": len(blob) - offset, "target": target})
        result = {"bufferView": len(buffer_views) - 1, "componentType": component_type, "count": len(values), "type": value_type}
        if bounds:
            result["min"] = [min(v[i] for v in values) for i in range(count)]
            result["max"] = [max(v[i] for v in values) for i in range(count)]
        accessors.append(result)
        return len(accessors) - 1

    primitives = []
    for geometry, material in parts:
        assert len(geometry["positions"]) < 65536, f"{name}: too many vertices for u16 indices"
        primitives.append({
            "attributes": {
                "POSITION": accessor(geometry["positions"], 5126, "VEC3", 34962, True),
                "NORMAL": accessor(geometry["normals"], 5126, "VEC3", 34962),
                "TEXCOORD_0": accessor(geometry["uvs"], 5126, "VEC2", 34962),
            },
            "indices": accessor(geometry["indices"], 5123, "SCALAR", 34963),
            "material": material,
        })

    gltf = {
        "asset": {"version": "2.0", "generator": "fusion arena generator"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"name": name, "mesh": 0}],
        "meshes": [{"name": name, "primitives": primitives}],
        "materials": [{k: v for k, v in m.items() if not k.startswith("_")} for m in materials],
        "accessors": accessors,
        "bufferViews": buffer_views,
        "buffers": [{"uri": f"{name}.bin", "byteLength": len(blob)}],
    }
    if images:
        gltf["images"] = [{"uri": "../" + path} for path in images]
        gltf["textures"] = [{"source": i, "sampler": 0} for i in range(len(images))]
        gltf["samplers"] = [{"magFilter": 9729, "minFilter": 9987, "wrapS": 10497, "wrapT": 10497}]

    (MESH_DIR / f"{name}.bin").write_bytes(blob)
    (MESH_DIR / f"{name}.gltf").write_text(json.dumps(gltf, indent=2) + "\n")
    for stale in MATERIAL_DIR.glob(f"{name}_*.zamat"):
        stale.unlink()
    for material in materials:
        if material["_hud"] or material["_anisotropy"] > 1:
            write_material(name, material, images)
    return asset_id(f"meshes/{name}.gltf")


def pbr(name, color, metallic=0.0, roughness=0.8, emissive=(0, 0, 0), texture=None, double_sided=False,
        emissive_texture=None, hud=False, anisotropy=1):
    """A glTF material. `texture` and `emissive_texture` index the mesh's
    images. glTF cannot express `hud` (drawn on top of everything, without a
    depth test) or `anisotropy` (sharper textures at grazing angles), so those
    materials also get a handwritten .zamat, which the cooker prefers."""
    material = {
        "name": name,
        "pbrMetallicRoughness": {"baseColorFactor": list(color), "metallicFactor": metallic, "roughnessFactor": roughness},
        "_hud": hud,
        "_anisotropy": anisotropy,
    }
    if texture is not None:
        material["pbrMetallicRoughness"]["baseColorTexture"] = {"index": texture}
    if emissive_texture is not None:
        material["emissiveTexture"] = {"index": emissive_texture}
    if any(emissive):
        material["emissiveFactor"] = list(emissive)
    if double_sided or hud:
        material["doubleSided"] = True
    return material


def number(value):
    """A TOML float the material cooker will not mistake for an integer."""
    return f"{float(value):.4f}"


def write_material(mesh_name, material, images):
    """The handwritten .zamat the cooker uses instead of generating one from
    the glTF material."""
    pbr_params = material["pbrMetallicRoughness"]
    color = pbr_params["baseColorFactor"]
    emissive = material.get("emissiveFactor", [0, 0, 0])
    double_sided = material.get("doubleSided", False)
    hud = material["_hud"]

    lines = [
        f"# {mesh_name}: {material['name']}. Written by tools/generate_arena.py.",
        "[material]",
        'shader = "fusion/standard"',
        "",
        "[render_state]",
        f'alpha_mode = "{"alpha_blend" if hud else "solid"}"',
        f"double_sided = {'true' if double_sided else 'false'}",
        f'cull_mode = "{"none" if double_sided else "back"}"',
    ]
    if hud:
        lines += ["depth_test = false", "depth_write = false", 'blend_mode = "alpha"']

    def texture_section(slot, path):
        return ["", f"[texture.{slot}]", f'path = "{path}"', 'mip_filter = "linear"',
                'wrap_s = "repeat"', 'wrap_t = "repeat"', f"max_anisotropy = {material['_anisotropy']}"]

    if "baseColorTexture" in pbr_params:
        lines += texture_section("u_albedo", images[pbr_params["baseColorTexture"]["index"]])
    if "emissiveTexture" in material:
        lines += texture_section("u_emissive_map", images[material["emissiveTexture"]["index"]])

    lines += [
        "",
        "[params]",
        f"u_base_color = [{', '.join(number(c) for c in color)}]",
        f"u_metallic = {number(pbr_params['metallicFactor'])}",
        f"u_roughness = {number(pbr_params['roughnessFactor'])}",
        f"u_emissive = [{', '.join(number(c) for c in emissive)}]",
    ]
    (MATERIAL_DIR / f"{mesh_name}_{material['name']}.zamat").write_text("\n".join(lines) + "\n")


# --------------------------------------------------------------- texture


def write_png(path, width, height, pixel):
    rows = bytearray()
    for y in range(height):
        rows.append(0)
        for x in range(width):
            rows.extend(pixel(x, y))

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(rows), 9))
    png += chunk(b"IEND", b"")
    path.write_bytes(png)


def grid_pixel(x, y, size=256):
    """One texture repeat = 2 m: a bright major line on the border, faint
    minor lines every 0.5 m. Tinted per material by baseColorFactor."""
    cell = size // 4

    def distance_to_line(value, spacing):
        offset = value % spacing
        return min(offset, spacing - 1 - offset)

    major = min(distance_to_line(x, size), distance_to_line(y, size))
    minor = min(distance_to_line(x, cell), distance_to_line(y, cell))
    if major <= 1:
        value = 235
    elif minor == 0:
        value = 175
    else:
        # Very subtle checker so large floors still read as moving surfaces.
        value = 140 if ((x // cell) + (y // cell)) % 2 else 148
    return (value, value, value)


def sky_pixel(x, y, height=256):
    """Vertical gradient, top row = zenith. The dome's v runs 0 (top) to 1."""
    t = y / (height - 1)
    stops = [
        (0.00, (38, 74, 140)),
        (0.42, (110, 150, 205)),
        (0.50, (196, 210, 226)),
        (0.56, (120, 124, 132)),
        (1.00, (60, 62, 68)),
    ]
    for (t0, c0), (t1, c1) in zip(stops, stops[1:]):
        if t <= t1:
            k = (t - t0) / (t1 - t0)
            return tuple(round(a + (b - a) * k) for a, b in zip(c0, c1))
    return stops[-1][1]


# --------------------------------------------------------------- meshes


def build_meshes():
    MESH_DIR.mkdir(parents=True, exist_ok=True)
    TEXTURE_DIR.mkdir(parents=True, exist_ok=True)
    MATERIAL_DIR.mkdir(parents=True, exist_ok=True)
    write_png(TEXTURE_DIR / "arena_grid.png", 256, 256, grid_pixel)
    write_png(TEXTURE_DIR / "arena_sky.png", 4, 256, sky_pixel)
    grid = ["textures/arena_grid.png"]

    ids = {}
    ids["floor"] = write_gltf(
        "arena_floor",
        [(box((0, 0, 0), FLOOR_SIZE, uv_tile=2.0), 0)],
        [pbr("GridFloor", (0.30, 0.34, 0.40, 1), roughness=0.9, texture=0, anisotropy=8)],
        grid,
    )
    ids["wall_x"] = write_gltf(
        "arena_wall_x",
        [(box((0, 0, 0), WALL_X_SIZE, uv_tile=2.0), 0)],
        [pbr("GridWall", (0.55, 0.58, 0.64, 1), roughness=0.85, texture=0, anisotropy=8)],
        grid,
    )
    ids["wall_z"] = write_gltf(
        "arena_wall_z",
        [(box((0, 0, 0), WALL_Z_SIZE, uv_tile=2.0), 0)],
        [pbr("GridWall", (0.55, 0.58, 0.64, 1), roughness=0.85, texture=0, anisotropy=8)],
        grid,
    )
    # Unit cube; scaled per entity for stairs, pillars, platforms, and cover.
    ids["block"] = write_gltf(
        "arena_block",
        [(box((0, 0, 0), (1, 1, 1)), 0)],
        [pbr("Concrete", (0.56, 0.53, 0.48, 1), roughness=0.92)],
    )

    # Crate: a dark frame around each of the 12 edges, orange panels inset.
    frame = []
    t = 0.09
    for axis in range(3):
        for a in (-0.5 + t / 2, 0.5 - t / 2):
            for b in (-0.5 + t / 2, 0.5 - t / 2):
                center = [0, 0, 0]
                size = [t, t, t]
                center[(axis + 1) % 3], center[(axis + 2) % 3] = a, b
                size[axis] = 1.0
                frame.append(box(tuple(center), tuple(size)))
    ids["crate"] = write_gltf(
        "arena_crate",
        [
            (box((0, 0, 0), (0.96, 0.96, 0.96)), 0),
            (merge(*frame), 1),
        ],
        [
            pbr("CratePanel", (0.93, 0.42, 0.10, 1), metallic=0.1, roughness=0.55),
            pbr("CrateFrame", (0.07, 0.08, 0.09, 1), metallic=0.6, roughness=0.4),
        ],
    )

    # Bullseye facing +Z, radius 0.5. Rings step forward so none z-fight.
    rings = []
    for i, radius in enumerate((0.5, 0.40, 0.30, 0.20, 0.10)):
        disc = cylinder(radius, 0.04, segments=32)
        rings.append((transformed(disc, offset=(0, 0, 0.02 + i * 0.012)), 1 if i % 2 else 0))
    ids["target"] = write_gltf(
        "target",
        [
            (transformed(cylinder(0.54, 0.06, segments=32), offset=(0, 0, -0.01)), 2),
            *rings,
            (box((0, 0, -0.08), (0.14, 0.14, 0.1)), 2),
        ],
        [
            pbr("TargetWhite", (0.92, 0.92, 0.90, 1), roughness=0.5),
            pbr("TargetRed", (0.85, 0.06, 0.05, 1), roughness=0.4, emissive=(0.35, 0.02, 0.01)),
            pbr("TargetBack", (0.24, 0.26, 0.30, 1), metallic=0.3, roughness=0.45),
        ],
    )

    # First-person blaster in meters; barrel points down -Z, origin near the
    # top of the grip so the view model offset reads naturally.
    ids["blaster"] = write_gltf(
        "blaster",
        [
            (merge(
                box((0, 0, -0.06), (0.07, 0.085, 0.30)),
                box((0, 0.058, -0.03), (0.026, 0.03, 0.17)),
                box((0, 0.004, 0.12), (0.06, 0.075, 0.07)),
                transformed(cylinder(0.017, 0.16, segments=12), offset=(0, 0.012, -0.30)),
            ), 0),
            (merge(
                box((0, 0.012, -0.235), (0.058, 0.064, 0.09)),
                box((0, 0.078, 0.035), (0.03, 0.012, 0.03)),
            ), 1),
            (merge(
                transformed(box((0, -0.06, 0), (0.045, 0.12, 0.05)), rotate_x(0.28), (0, -0.03, 0.05)),
                box((0, -0.06, -0.035), (0.012, 0.035, 0.05)),
            ), 2),
            (merge(
                box((0.037, -0.004, -0.06), (0.008, 0.026, 0.15)),
                box((-0.037, -0.004, -0.06), (0.008, 0.026, 0.15)),
                transformed(cylinder(0.022, 0.02, segments=12), offset=(0, 0.012, -0.385)),
            ), 3),
        ],
        [
            pbr("Gunmetal", (0.30, 0.32, 0.36, 1), metallic=0.5, roughness=0.42),
            pbr("Accent", (0.95, 0.40, 0.08, 1), metallic=0.25, roughness=0.4),
            pbr("Grip", (0.07, 0.07, 0.08, 1), roughness=0.85),
            pbr("EnergyCell", (0.10, 0.55, 0.65, 1), roughness=0.3, emissive=(0.25, 2.4, 2.8)),
        ],
    )

    # Energy bolt: an ellipsoid 1 wide and 3.5 long; the game scales it.
    ids["bolt"] = write_gltf(
        "bolt",
        [(sphere(0.5, segments=12, rings=8, stretch_z=3.5), 0)],
        [pbr("Bolt", (0.05, 0.6, 1.0, 1), roughness=0.2, emissive=(0.15, 1.6, 2.6))],
    )
    ids["spark"] = write_gltf(
        "spark",
        [(octahedron(0.5), 0)],
        [pbr("Spark", (1.0, 0.55, 0.15, 1), roughness=0.3, emissive=(3.0, 1.2, 0.2))],
    )
    ids["muzzle_flash"] = write_gltf(
        "muzzle_flash",
        [(merge(
            quad((0, 0, 0), (1, 0.18)),
            transformed(quad((0, 0, 0), (1, 0.18)), rotate_z(math.pi / 2)),
            transformed(quad((0, 0, 0), (0.7, 0.14)), rotate_z(math.pi / 4)),
            transformed(quad((0, 0, 0), (0.7, 0.14)), rotate_z(-math.pi / 4)),
            transformed(quad((0, 0, 0), (0.18, 1.2)), rotate_x(math.pi / 2)),
        ), 0)],
        [pbr("MuzzleFlash", (1.0, 0.8, 0.4, 1), roughness=1.0, emissive=(2.6, 1.7, 0.5), double_sided=True)],
    )

    # HUD meshes sit 0.2 m in front of the eye; `px` is roughly one pixel of
    # an editor-sized viewport at the arena's field of view.
    px = 0.00042
    arm, thick, gap = 9 * px, 2 * px, 5 * px
    ids["crosshair"] = write_gltf(
        "crosshair",
        [(merge(
            quad((0, gap + arm / 2, 0), (thick, arm)),
            quad((0, -gap - arm / 2, 0), (thick, arm)),
            quad((gap + arm / 2, 0, 0), (arm, thick)),
            quad((-gap - arm / 2, 0, 0), (arm, thick)),
            quad((0, 0, 0), (thick, thick)),
        ), 0)],
        [pbr("Crosshair", (0, 0, 0, 0.9), roughness=1.0, emissive=(2.5, 3.0, 3.0), hud=True)],
    )
    marker_arm = 7 * px
    marker_offset = gap + 2 * px + marker_arm / 2
    marker = []
    for angle in (math.pi / 4, 3 * math.pi / 4, 5 * math.pi / 4, 7 * math.pi / 4):
        bar = quad((marker_offset, 0, 0), (marker_arm, thick * 1.2))
        marker.append(transformed(bar, rotate_z(angle)))
    ids["hit_marker"] = write_gltf(
        "hit_marker",
        [(merge(*marker), 0)],
        [pbr("HitMarker", (0, 0, 0, 0.95), roughness=1.0, emissive=(4.0, 1.2, 0.5), hud=True)],
    )

    # Sky: an inward-facing dome lit only by its gradient texture, since the
    # renderer's clear color is a flat grey.
    dome = sphere(SKY_RADIUS, segments=32, rings=16)
    dome["normals"] = [tuple(-c for c in n) for n in dome["normals"]]
    dome["indices"] = [i for a, b, c in zip(*[iter(dome["indices"])] * 3) for i in (a, c, b)]
    ids["sky"] = write_gltf(
        "sky_dome",
        [(dome, 0)],
        [pbr("Sky", (0, 0, 0, 1), roughness=1.0, emissive=(1, 1, 1), emissive_texture=0)],
        ["textures/arena_sky.png"],
    )
    return ids


